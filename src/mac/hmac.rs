    // Test 1: Key length equals the block length (64 bytes)
    #[test]
    fn test_hmac_sha1_keylen_eq_blocklen() {
        let data = [
            0x53, 0x61, 0x6D, 0x70, 0x6C, 0x65, 0x20, 0x6D, 0x65, 0x73, 0x73, 0x61, 0x67, 0x65, 0x20, 0x66,
            0x6F, 0x72, 0x20, 0x6B, 0x65, 0x79, 0x6C, 0x65, 0x6E, 0x3D, 0x62, 0x6C, 0x6F, 0x63, 0x6B, 0x6C,
            0x65, 0x6E
        ]; // "Sample message for keylen=blocklen"
        let key = (0x00..=0x3F).collect::<Vec<u8>>();

        let ref_ = [
            0x5F, 0xD5, 0x96, 0xEE, 0x78, 0xD5, 0x55, 0x3C, 0x8F, 0xF4, 0xE7, 0x2D, 0x26, 0x6D, 0xFD, 0x19,
            0x23, 0x66, 0xDA, 0x29
        ];

        let res = HMAC::<SHA1>::compute(data.as_slice(), key);
        assert_eq!(res, ref_);
    }

