#[cfg(test)]
mod tests_slhdsa_sha2_sign {
    use std::path::PathBuf;
    use crate::pqc::slh_dsa::slh_dsa::SLHDSAPrivateKey;
    use super::*;
    use serde::Deserialize;
    use rstest::rstest;

    #[derive(Deserialize)]
    struct TestVector {
        #[serde(default)]
        parameter_set: String,
        #[serde(with = "hex::serde")]
        sk: Vec<u8>,
        #[serde(with = "hex::serde")]
        message: Vec<u8>,
        #[serde(with = "hex::serde")]
        context: Vec<u8>,
        #[serde(with = "hex::serde")]
        signature: Vec<u8>,
        #[serde(default)]
        deterministic: bool,
        #[serde(default)]
        hash: String,
    }

    #[rstest]
    fn test_sha2_vectors(#[files("src/pqc/slh_dsa/test_data/sign/*json")] path: PathBuf) {
        let content = std::fs::read_to_string(&path).expect("Failed to read test vector file");
        let tv: TestVector = serde_json::from_str(content.as_str()).expect("Failed to parse test vector JSON");

        macro_rules! run_test {
            ($constructor: expr, $key_len: literal, $deterministic: expr) => {{
                let slh = $constructor;
                let sk = SLHDSAPrivateKey::<$key_len>::from_bytes(&tv.sk);
                let res = slh.sign(&tv.message, &tv.context, &sk, $deterministic);
                assert_eq!(res.as_bytes(), tv.signature);
            }};
        }

        match tv.parameter_set.as_str() {
            "sha2_128s" => run_test!(SLHDSA::sha2_128s(), 16, tv.deterministic),
            "sha2_128f" => run_test!(SLHDSA::sha2_128f(), 16, tv.deterministic),
            "sha2_192s" => run_test!(SLHDSA::sha2_192s(), 24, tv.deterministic),
            "sha2_192f" => run_test!(SLHDSA::sha2_192f(), 24, tv.deterministic),
            "sha2_256s" => run_test!(SLHDSA::sha2_256s(), 32, tv.deterministic),
            "sha2_256f" => run_test!(SLHDSA::sha2_256f(), 32, tv.deterministic),
            unsupported => panic!("Unsupported parameter set in file {:?}: {}", path, unsupported),
        }

    }
}